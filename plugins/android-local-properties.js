const { withDangerousMod } = require('expo/config-plugins');
const path = require('path');
const fs = require('fs');
const os = require('os');

/**
 * Config plugin to automatically generate local.properties file for Android builds
 */
function withAndroidLocalProperties(config) {
  return withDangerousMod(config, [
    'android',
    async (config) => {
      const projectRoot = config.modRequest.projectRoot;
      const androidProjectRoot = path.join(projectRoot, 'android');
      const localPropertiesPath = path.join(androidProjectRoot, 'local.properties');

      // Try to find Android SDK path automatically
      const androidSdkPath = findAndroidSdkPath();
      
      if (androidSdkPath) {
        const content = `# Auto-generated by expo-local-properties-plugin during prebuild
# This file was auto-generated to handle Android SDK path configuration
sdk.dir=${androidSdkPath.replace(/\\/g, '\\\\')}
`;

        // Ensure android directory exists
        if (!fs.existsSync(androidProjectRoot)) {
          fs.mkdirSync(androidProjectRoot, { recursive: true });
        }

        // Write the local.properties file
        fs.writeFileSync(localPropertiesPath, content);
        
        console.log(`✅ Generated local.properties with SDK path: ${androidSdkPath}`);
      } else {
        console.warn(`⚠️  Could not automatically detect Android SDK path. Please set ANDROID_HOME environment variable or manually create local.properties file.`);
      }

      return config;
    },
  ]);
}

/**
 * Attempts to find Android SDK path from common locations
 */
function findAndroidSdkPath() {
  // Check environment variables first
  const androidHome = process.env.ANDROID_HOME || process.env.ANDROID_SDK_ROOT;
  if (androidHome && fs.existsSync(androidHome)) {
    return androidHome;
  }

  // Common Android SDK locations by platform
  const possiblePaths = [];
  
  if (process.platform === 'win32') {
    const userHome = os.homedir();
    possiblePaths.push(
      path.join(userHome, 'AppData', 'Local', 'Android', 'Sdk'),
      'C:\\Android\\Sdk',
      'C:\\Users\\' + os.userInfo().username + '\\AppData\\Local\\Android\\Sdk'
    );
  } else if (process.platform === 'darwin') {
    const userHome = os.homedir();
    possiblePaths.push(
      path.join(userHome, 'Library', 'Android', 'sdk'),
      path.join(userHome, 'Android', 'Sdk')
    );
  } else {
    // Linux
    const userHome = os.homedir();
    possiblePaths.push(
      path.join(userHome, 'Android', 'Sdk'),
      path.join(userHome, 'android-sdk'),
      '/opt/android-sdk'
    );
  }

  // Check each possible path
  for (const sdkPath of possiblePaths) {
    if (fs.existsSync(sdkPath)) {
      // Verify it's a valid Android SDK by checking for platform-tools
      const platformToolsPath = path.join(sdkPath, 'platform-tools');
      if (fs.existsSync(platformToolsPath)) {
        return sdkPath;
      }
    }
  }

  return null;
}

module.exports = withAndroidLocalProperties; 